"""XYZ v2 task tracking and bounded recovery with the pinned PiPER model."""
from copy import deepcopy
import math
from pathlib import Path
import unittest

import numpy as np
from scipy.spatial.transform import Rotation

from servo_bridge.cartesian_policy import CartesianPolicy
from servo_bridge.core import load_config


PROFILE = Path(__file__).resolve().parents[1] / 'config.cartesian.example.json'


def pad(**buttons):
    return dict(connected=True, instance=1, axes={}, buttons=buttons, hat=[0, 0])


class CartesianPolicyTests(unittest.TestCase):
    def setUp(self):
        self.cfg = load_config(PROFILE)
        self.dt = self.cfg['publish_period_s']
        self.q = np.radians(self.cfg['sim_initial_joints_deg'])
        self.policy = CartesianPolicy(self.cfg)

    def step(self, sample, q=None):
        q = self.q if q is None else q
        rotation = self.policy.kin.forward(q)[:3, :3]
        return self.policy.step(sample, rotation, self.dt, measured_q=q)

    def arm(self):
        self.step(pad())

    def test_lb_rb_start_disconnect_and_neutral_hold(self):
        sample = pad(lb=True)
        sample['axes']['left_y'] = -1
        np.testing.assert_array_equal(self.step(sample), 0)
        self.arm()
        self.assertGreater(np.linalg.norm(self.step(sample)), 0)
        np.testing.assert_array_equal(self.step(pad()), 0)
        np.testing.assert_array_equal(self.step(pad(rb=True)), 0)
        sample['buttons']['start'] = True
        np.testing.assert_array_equal(self.step(sample), 0)
        self.assertTrue(self.policy.faulted)
        self.step(pad())
        np.testing.assert_array_equal(self.step(pad(lb=True)), 0)

    def test_closed_loop_xyz_directions_and_joint_acceleration(self):
        inputs = [('left_y', -1, 0, 1), ('left_x', 1, 1, -1), ('right_y', -1, 2, 1)]
        for key, value, axis, sign in inputs:
            for direction in (-1, 1):
                with self.subTest(key=key, direction=direction):
                    self.policy = CartesianPolicy(self.cfg)
                    q = self.q.copy()
                    start = self.policy.kin.forward(q)[:3, 3]
                    self.step(pad(), q)
                    sample = pad(lb=True)
                    sample['axes'][key] = value * direction * .4
                    previous = np.zeros(6)
                    for _ in range(40):
                        velocity = self.step(sample, q)
                        self.assertFalse(self.policy.pause, self.policy.diagnostics)
                        self.assertLessEqual(np.max(abs(velocity)), math.radians(24)+1e-8)
                        self.assertLessEqual(np.max(abs(velocity-previous)), math.radians(60)*self.dt+1e-7)
                        q += velocity*self.dt
                        previous = velocity
                    delta = self.policy.kin.forward(q)[:3, 3]-start
                    self.assertGreater(delta[axis]*sign*direction, .01)
                    self.assertLess(np.linalg.norm(np.delete(delta, axis)), .002)

    def test_six_dimensional_singularity_does_not_block_feasible_translation(self):
        q = np.radians([45.28, 90.38, -50.58, -1.33, 13.38, 0])
        _, jac = self.policy.kin.forward(q, jacobian=True)
        self.assertGreater(np.linalg.cond(jac), 30)
        twist = np.array([-.0291, 0, -.0525, 0, 0, 0])
        for _ in range(40):
            velocity = self.policy.solve(q, q, jac, twist, np.zeros(3), math.radians(15), self.dt)
            self.policy.previous = velocity
        self.assertFalse(self.policy.pause, self.policy.diagnostics)
        self.assertGreater(self.policy.diagnostics['progress'], .9)
        self.assertLess(np.linalg.norm(jac[:3]@velocity-twist[:3]), .003)

    def test_j5_boundary_avoids_outward_motion_and_can_retreat(self):
        q = np.radians([-4.9, 86.89, -48.98, -14.36, 67.51, -30.4])
        _, jac = self.policy.kin.forward(q, jacobian=True)
        for _ in range(40):
            velocity = self.policy.solve(q, q, jac, np.array([0, 0, .06, 0, 0, 0]),
                                         np.zeros(3), math.radians(15), self.dt)
            self.policy.previous = velocity
        self.assertFalse(self.policy.pause, self.policy.diagnostics)
        self.assertLessEqual(velocity[4], 1e-8)
        self.assertGreater((jac@velocity)[2], .04)
        self.policy.reset_motion()
        # Ask for the Cartesian twist generated by a known inward J5 jog.
        inward = jac[:, 4] * -.1
        for _ in range(40):
            velocity = self.policy.solve(q, q, jac, inward, np.zeros(3), math.radians(15), self.dt)
            self.policy.previous = velocity
        self.assertFalse(self.policy.pause, self.policy.diagnostics)
        self.assertLess(velocity[4], -.02)

    def test_joint_limits_and_orientation_envelope_in_long_translation(self):
        self.arm()
        q = self.q.copy()
        sample = pad(lb=True)
        sample['axes']['right_y'] = -.6
        initial = self.policy.kin.forward(q)[:3, :3]
        pauses = 0
        for _ in range(350):
            velocity = self.step(sample, q)
            pauses += self.policy.pause
            q += velocity*self.dt
            self.assertTrue(np.all(q >= self.policy.kin.low))
            self.assertTrue(np.all(q <= self.policy.kin.high))
            rotation = self.policy.kin.forward(q)[:3, :3]
            drift = np.linalg.norm(Rotation.from_matrix(initial@rotation.T).as_rotvec())
            self.assertLess(drift, self.cfg['cartesian_orientation_drift_rad']+.005)
        self.assertLess(pauses, 350)

    def test_position_and_hold_modes_and_fine_speed(self):
        for mode, expected in [('position', .03), ('hold', .03)]:
            self.policy = CartesianPolicy({**self.cfg, 'cartesian_orientation_mode': mode})
            self.arm()
            sample = pad(lb=True, rb=True)
            sample['axes']['left_y'] = -1
            for _ in range(80):
                velocity = self.step(sample)
                self.assertLessEqual(np.max(abs(velocity)), math.radians(8)+1e-8)
            self.assertFalse(self.policy.pause, self.policy.diagnostics)
            achieved = self.policy.diagnostics['achieved_twist']
            self.assertAlmostEqual(achieved[0], expected, delta=.002)

    def test_hold_mode_preserves_heading_in_closed_loop(self):
        self.policy = CartesianPolicy({**self.cfg, 'cartesian_orientation_mode': 'hold'})
        self.arm()
        q = self.q.copy()
        initial = self.policy.kin.forward(q)
        sample = pad(lb=True)
        sample['axes']['right_y'] = -.4
        for _ in range(150):
            q += self.step(sample, q)*self.dt
            pose = self.policy.kin.forward(q)
            drift = np.linalg.norm(Rotation.from_matrix(initial[:3, :3]@pose[:3, :3].T).as_rotvec())
            self.assertLess(drift, self.cfg['cartesian_hold_drift_rad']+.002)
        self.assertGreater(self.policy.kin.forward(q)[2, 3]-initial[2, 3], .02)

    def test_invalid_model_or_input_is_not_recoverable_geometry(self):
        self.arm()
        sample = pad(lb=True)
        sample['axes']['left_y'] = float('nan')
        with self.assertRaises(ValueError):
            self.step(sample)
        for settings in ({'cartesian_joint_margin_rad': .04},
                         {'cartesian_orientation_mode': 'unknown'},
                         {'cartesian_orientation_drift_rad': float('inf')}):
            with self.subTest(settings=settings), self.assertRaises(ValueError):
                CartesianPolicy({**self.cfg, **settings})


if __name__ == '__main__':
    unittest.main()
